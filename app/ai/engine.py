"""AI decision engine: turns a stream of proctoring events into a fraud score.

The score combines three signals:

* **Severity** – each event type has a base weight (editable by the admin).
* **Frequency** – repeats of the same behaviour count progressively more
  (1x, 1.25x, 1.5x ... capped at 2x) because a pattern is stronger evidence
  than a one-off glance.
* **Recency** – minor behavioural events fade with a half-life so a student
  is not punished for the whole exam because of one early mistake, while
  hard evidence (phone, different person, second person) never decays.

On top of that, correlation rules detect combinations that are much more
suspicious together than apart (e.g. looking away while someone is talking).
The raw points are squashed to 0-100 with a saturating curve so the score is
comparable across exams of any length.
"""

